export const SVG_MODEL_CONSTANTS = {
  midX: 824,
  waistY: 955,
  stageScale: 0.85,
  puppytScaleFactor: 0.85 / PUPPYT_TO_EVOLVED_SCALE,
  pelvisPuppytPivot: [1257, 3382] as const,
} as const;

function svgPt(sx: number, sy: number): readonly [number, number] {
  return [
    SVG_MODEL_CONSTANTS.pelvisPuppytPivot[0] +
      (sx - SVG_MODEL_CONSTANTS.midX) * SVG_MODEL_CONSTANTS.puppytScaleFactor,
    SVG_MODEL_CONSTANTS.pelvisPuppytPivot[1] +
      (sy - SVG_MODEL_CONSTANTS.waistY) * SVG_MODEL_CONSTANTS.puppytScaleFactor,
  ] as const;
}

function svgMirrorPt(sx: number, sy: number): readonly [number, number] {
  return svgPt(SVG_MODEL_CONSTANTS.midX * 2 - sx, sy);
}

